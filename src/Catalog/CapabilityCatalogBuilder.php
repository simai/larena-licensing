<?php

declare(strict_types=1);

namespace Larena\Licensing\Catalog;

/**
 * Builds the shipped catalog from the Specs capability registry (`specs/capabilities/registry.json`: id, package,
 * kind, default tier, trial, and the area, needs and always-on mark Specs keeps in `specs/capabilities/placement.json`),
 * and checks a catalog: areas, needs, cycles and words in every language. A capability the registry marks `planned`
 * is not built yet and is left out. `scripts/refresh-capability-catalog.php` writes it and, in the package gate,
 * compares the shipped one with a fresh build whenever the Specs checkout is there.
 */
final class CapabilityCatalogBuilder
{
    public const string SCHEMA = 'larena.capability_catalog';

    public const array TIERS = ['free', 'trial', 'paid', 'enterprise'];

    public const string WORDS = 'larena-licensing::capabilities.';

    /**
     * @param array<string, mixed> $registry
     * @return array<string, mixed>
     */
    public static function build(array $registry): array
    {
        $baselines = [];
        foreach (is_array($registry['packages'] ?? null) ? $registry['packages'] : [] as $package) {
            if (is_array($package) && is_string($package['package_id'] ?? null) && is_string($package['baseline_capability_id'] ?? null)) {
                $baselines[$package['package_id']] = $package['baseline_capability_id'];
            }
        }
        $entries = [];
        foreach (is_array($registry['capabilities'] ?? null) ? $registry['capabilities'] : [] as $capability) {
            if (!is_array($capability) || !is_string($capability['id'] ?? null) || self::planned($capability)) {
                continue;
            }
            $id = $capability['id'];
            $package = (string) ($capability['package'] ?? '');
            $kind = (string) ($capability['kind'] ?? '');
            $requires = is_array($capability['needs'] ?? null) ? array_values(array_filter($capability['needs'], 'is_string')) : [];
            // A feature of a package needs the package's own baseline.
            if ($kind !== 'package_baseline' && isset($baselines[$package]) && $baselines[$package] !== $id) {
                $requires[] = $baselines[$package];
            }
            $requires = array_values(array_unique($requires));
            sort($requires, SORT_STRING);
            $words = self::WORDS . 'items.' . self::slug($id);
            $entries[$id] = [
                'id' => $id,
                'package' => $package,
                'kind' => $kind,
                'tier' => (string) ($capability['default_tier'] ?? ''),
                'trial_eligible' => ($capability['trial_eligible'] ?? false) === true,
                'area' => is_string($capability['area'] ?? null) ? $capability['area'] : '',
                'always_on' => ($capability['always_on'] ?? false) === true,
                'requires' => $requires,
                'title_key' => $words . '.title',
                'description_key' => $words . '.description',
            ];
        }
        ksort($entries, SORT_STRING);

        return [
            'schema' => self::SCHEMA,
            'schema_version' => 1,
            'comment' => 'Generated by composer run catalog:refresh from the Specs capability registry; do not edit by hand.',
            'source' => [
                'registry_id' => (string) ($registry['registry_id'] ?? ''),
                'registry_schema' => (string) ($registry['schema'] ?? ''),
                'capability_count' => count($entries),
            ],
            'areas' => is_array($registry['areas'] ?? null) ? array_values(array_filter($registry['areas'], 'is_string')) : [],
            'capabilities' => array_values($entries),
        ];
    }

    /**
     * What is wrong with a catalog: its own structure, and the words of every function and area in each language.
     *
     * @param array<string, mixed> $catalog
     * @param array<string, array<string, mixed>> $languages locale => the package's `capabilities.php` lines
     * @return list<string>
     */
    public static function errors(array $catalog, array $languages): array
    {
        $errors = [];
        if (($catalog['schema'] ?? null) !== self::SCHEMA) {
            $errors[] = 'catalog_schema_unknown';
        }
        $areas = is_array($catalog['areas'] ?? null) ? $catalog['areas'] : [];
        $entries = is_array($catalog['capabilities'] ?? null) ? $catalog['capabilities'] : [];
        if ($entries === []) {
            $errors[] = 'catalog_empty';
        }
        $ids = [];
        foreach ($entries as $entry) {
            $ids[(string) (is_array($entry) ? ($entry['id'] ?? '') : '')] = is_array($entry) ? $entry : [];
        }
        foreach ($ids as $id => $entry) {
            if (!str_starts_with($id, CapabilityCatalog::ID_PREFIX)) {
                $errors[] = 'capability_id_invalid:' . $id;
            }
            if (!in_array($entry['tier'] ?? null, self::TIERS, true)) {
                $errors[] = 'capability_tier_unknown:' . $id;
            }
            if (!in_array($entry['area'] ?? null, $areas, true)) {
                $errors[] = 'capability_area_unknown:' . $id;
            }
            if (($entry['always_on'] ?? false) === true && ($entry['tier'] ?? null) !== 'free') {
                $errors[] = 'capability_always_on_not_free:' . $id;
            }
            foreach (is_array($entry['requires'] ?? null) ? $entry['requires'] : [] as $required) {
                if (!isset($ids[$required])) {
                    $errors[] = 'capability_requires_unknown:' . $id . '>' . $required;
                } elseif ($required === $id) {
                    $errors[] = 'capability_requires_itself:' . $id;
                }
            }
            if (self::inCycle($ids, $id)) {
                $errors[] = 'capability_requires_cycle:' . $id;
            }
            foreach ($languages as $locale => $lines) {
                foreach (['title_key', 'description_key'] as $key) {
                    if (!self::hasWords($lines, (string) ($entry[$key] ?? ''))) {
                        $errors[] = 'capability_words_missing:' . $locale . ':' . $id . ':' . $key;
                    }
                }
            }
        }
        foreach ($areas as $area) {
            foreach ($languages as $locale => $lines) {
                if (!self::hasWords($lines, self::WORDS . 'areas.' . $area)) {
                    $errors[] = 'area_words_missing:' . $locale . ':' . $area;
                }
            }
        }

        return $errors;
    }

    /**
     * What the registry lacks for a catalog: its areas, and an area for every capability that is built (an older
     * registry, from before Specs kept areas and needs, has neither).
     *
     * @param array<string, mixed> $registry
     * @return list<string>
     */
    public static function registryErrors(array $registry): array
    {
        $errors = [];
        if (!is_array($registry['areas'] ?? null) || $registry['areas'] === []) {
            $errors[] = 'registry_areas_missing';
        }
        foreach (is_array($registry['capabilities'] ?? null) ? $registry['capabilities'] : [] as $capability) {
            if (is_array($capability) && is_string($capability['id'] ?? null) && !self::planned($capability)
                && (!is_string($capability['area'] ?? null) || !is_array($capability['needs'] ?? null))) {
                $errors[] = 'registry_capability_unplaced:' . $capability['id'];
            }
        }

        return $errors;
    }

    /** A capability declared ahead of its package: not built, not in the catalog. @param array<string, mixed> $capability */
    private static function planned(array $capability): bool
    {
        return ($capability['status'] ?? null) === 'planned';
    }

    /** The JSON the package ships: stable key order, two-space indent, one entry per line group. @param array<string, mixed> $catalog */
    public static function encode(array $catalog): string
    {
        return json_encode($catalog, JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE | JSON_THROW_ON_ERROR) . "\n";
    }

    /** `larena.capability.telephony.ai_voice_orchestration` → `telephony.ai_voice_orchestration`. */
    public static function slug(string $id): string
    {
        return str_starts_with($id, CapabilityCatalog::ID_PREFIX) ? substr($id, strlen(CapabilityCatalog::ID_PREFIX)) : $id;
    }

    /** @param array<string, mixed> $lines */
    private static function hasWords(array $lines, string $key): bool
    {
        if (!str_starts_with($key, self::WORDS)) {
            return false;
        }
        $value = $lines;
        foreach (explode('.', substr($key, strlen(self::WORDS))) as $part) {
            if (!is_array($value) || !array_key_exists($part, $value)) {
                return false;
            }
            $value = $value[$part];
        }

        return is_string($value) && trim($value) !== '';
    }

    /** @param array<string, array<string, mixed>> $entries */
    private static function inCycle(array $entries, string $start): bool
    {
        $stack = [[$start, []]];
        while ($stack !== []) {
            [$current, $path] = array_pop($stack);
            foreach (is_array($entries[$current]['requires'] ?? null) ? $entries[$current]['requires'] : [] as $next) {
                if ($next === $start) {
                    return true;
                }
                if (!isset($path[$next]) && isset($entries[$next])) {
                    $stack[] = [$next, $path + [$next => true]];
                }
            }
        }

        return false;
    }
}
